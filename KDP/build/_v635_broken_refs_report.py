"""Generate a focused report of dead/broken bibliography URLs."""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / 'KDP' / 'validation' / 'references_audit.csv'
OUT = ROOT / 'KDP' / 'BROKEN_REFERENCES.md'

bad = []
with SRC.open(encoding='utf-8') as f:
    for row in csv.DictReader(f):
        s = row.get('status', '')
        e = row.get('error', '')
        url = row.get('url', '')
        f_ = row.get('file', '')
        anno = row.get('annotation_first_60', '')
        # Categorize
        if s in ('200', '301', '302', '202'):
            continue
        if s == '403' and 'doi.org' in url:
            continue  # DOI 403 is normal (publisher paywall blocks bots)
        if s == '403' and any(host in url for host in ('cambridge.org', 'evolutionaryscale.ai', 'ml.gatech.edu')):
            continue  # Known bot-blockers; URL is valid in browser
        bad.append({
            'file': f_,
            'url': url,
            'status': s,
            'error': e,
            'annotation': anno,
        })

# Group by file
by_file = defaultdict(list)
for r in bad:
    by_file[r['file']].append(r)

with OUT.open('w', encoding='utf-8') as f:
    f.write('# Broken Bibliography References\n\n')
    f.write(f'Generated by `_v635_broken_refs_report.py` from `references_audit.csv`.\n\n')
    f.write(f'**{len(bad)} references** need attention across **{len(by_file)} files**.\n\n')
    f.write('Excluded: HTTP 403 from DOI/Cambridge/EvoScale (bot-blocked but valid in browser),\n')
    f.write('and HTTP 200/301/302/202 (working).\n\n---\n\n')
    for fname in sorted(by_file):
        f.write(f'## {fname}\n\n')
        for r in by_file[fname]:
            label = r['status'] if r['status'] else 'ERR'
            f.write(f'- **[{label}]** `{r["url"]}`\n')
            if r['annotation']:
                f.write(f'  - was: _{r["annotation"]}_\n')
            if r['error']:
                f.write(f'  - error: {r["error"][:100]}\n')
        f.write('\n')

print(f'Wrote {OUT}')
print(f'  {len(bad)} broken references in {len(by_file)} files')
