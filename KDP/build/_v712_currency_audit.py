"""9th edition Wave B5: scan the entire book for dated claims that will
go stale by the next edition. Produces a refresh queue grouped by
category: model citations, pricing, benchmark scores, dates, and
"as of <year>" phrases.

Read-only. Writes the report to KDP/build/_v712_currency_report.md
(gitignored or committed depending on preference).

Heuristics:
  * "as of <year>" or "as of <month> <year>"
  * "in (early|late|mid|H1|H2) (20XX)"
  * "(20XX)" in a sentence
  * Specific model versions: "GPT-4", "GPT-4o", "Claude 3.5", "Claude 4",
    "Gemini 1.5", "Gemini 2.0", "o1", "o3", "DeepSeek-R1", etc.
  * Price patterns: "$X per million tokens", "$X/MTok"
  * Benchmark patterns: "X% on (MMLU|SWE-bench|HumanEval|GSM8K|...)"

Each finding is reported with file:line, category, and quoted context.
"""
from __future__ import annotations
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
REPORT = ROOT / 'KDP' / 'build' / '_v712_currency_report.md'
SKIP = ('node_modules', '.git/', 'pagefind/', 'KDP/build/', 'KDP/output/',
        'templates/', '_archive/', 'temp_epub/', 'vendor/', '/agents/')

PATTERNS: list[tuple[str, re.Pattern]] = [
    ('asof', re.compile(
        r'\bas\s+of\s+(?:(?:January|February|March|April|May|June|July|August|'
        r'September|October|November|December|early|late|mid|Q[1-4]|H[12])\s+)?'
        r'20\d{2}\b', re.IGNORECASE)),
    ('year-phrase', re.compile(
        r'\bin\s+(?:early|late|mid|Q[1-4]|H[12])\s+20\d{2}\b', re.IGNORECASE)),
    ('model-version', re.compile(
        r'\b('
        r'GPT-4(?:o|\.5)?(?:-mini|-turbo)?|GPT-5(?:\.\d)?|GPT-4\.1|'
        r'Claude\s*(?:3(?:\.5)?(?:\s+Opus|\s+Sonnet|\s+Haiku)?|4|Opus\s*4|Sonnet\s*4)|'
        r'Gemini\s*(?:1\.5|2(?:\.0)?|3(?:\.0)?)\s*(?:Pro|Flash|Ultra)?|'
        r'(?<!\w)o[13](?:-mini|-preview)?(?!\w)|o3-mini|o4(?:-mini)?|'
        r'DeepSeek[-\s]?(?:R1|R2|V3|V2|Coder)|'
        r'Llama\s*(?:2|3(?:\.\d)?|4)|'
        r'Mistral(?:\s+(?:Large|Small|Medium|Nemo))?|Mixtral|'
        r'Qwen\s*\d+(?:\.\d)?|QwQ(?:-32B)?|'
        r'Gemma\s*\d+|'
        r'Phi-?\d+(?:\.\d)?'
        r')\b')),
    ('price', re.compile(
        r'\$[\d.]+\s*(?:per\s+(?:million\s+)?(?:input\s+|output\s+)?tokens?|/\s*M(?:Tok)?\b|'
        r'per\s+(?:1M|million|1K)\s+tokens?|/MTok)', re.IGNORECASE)),
    ('benchmark', re.compile(
        r'\b(\d{1,3}(?:\.\d+)?)\s*%\s*on\s*'
        r'(?:MMLU|HumanEval|SWE-?bench(?:\s+(?:Verified|Lite|Full))?|GSM8K|'
        r'MATH|HellaSwag|BBH|ARC(?:-AGI)?|GPQA(?:\s+Diamond)?|'
        r'CommonsenseQA|TruthfulQA|WinoGrande|WebArena|GAIA|'
        r'BFCL|MMMU|MMLU-Pro|Codeforces|TAU-bench)\b', re.IGNORECASE)),
    ('cutoff', re.compile(
        r'\b(?:training\s+cutoff|knowledge\s+cutoff|cutoff\s+date)\b',
        re.IGNORECASE)),
]


def main() -> int:
    by_file: dict[str, list[tuple[str, str]]] = defaultdict(list)
    by_category: dict[str, int] = defaultdict(int)
    total = 0
    for p in sorted(ROOT.rglob('*.html')):
        sp = str(p).replace('\\', '/')
        if any(s in sp for s in SKIP):
            continue
        text = p.read_text(encoding='utf-8', errors='replace')
        # Strip <code>, <pre>, <script>, <style> blocks so we don't flag
        # code or doc-string examples.
        text_prose = re.sub(
            r'<(?:code|pre|script|style)\b[^>]*>.*?</(?:code|pre|script|style)>',
            ' ', text, flags=re.DOTALL | re.IGNORECASE)
        # Also strip HTML tags so they don't contaminate quoted context
        text_prose_clean = re.sub(r'<[^>]+>', ' ', text_prose)
        # We still need to compute line numbers in the ORIGINAL file, so
        # iterate the prose-cleaned version while preserving offsets.
        for cat, pat in PATTERNS:
            for m in pat.finditer(text_prose):
                # Skip if the match is inside a stripped region (it would
                # have been replaced with spaces).
                ctx_start = max(0, m.start() - 60)
                ctx_end = min(len(text_prose), m.end() + 60)
                ctx = re.sub(r'\s+', ' ',
                             re.sub(r'<[^>]+>', '', text_prose[ctx_start:ctx_end])).strip()
                line = text_prose.count('\n', 0, m.start()) + 1
                # Compute the line in the original file
                # (approx since we replaced code blocks with spaces of
                # equal length).
                by_file[sp].append((f'{cat}:L{line}', ctx))
                by_category[cat] += 1
                total += 1
    # Write report
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    with REPORT.open('w', encoding='utf-8') as f:
        f.write('# Currency Refresh Queue\n\n')
        f.write(f'_Generated by `_v712_currency_audit.py`. Total findings: '
                f'**{total}** across {len(by_file)} files._\n\n')
        f.write('## Summary by category\n\n')
        f.write('| Category | Count | What to refresh |\n|---|---:|---|\n')
        cat_help = {
            'asof': 'Replace "as of 2025" with the latest review date.',
            'year-phrase': 'Update year-anchored claims to the publication-year reference.',
            'model-version': 'Verify model version is still the SOTA in its category; bump if a newer release supersedes it.',
            'price': 'Verify token pricing against the provider\'s current rate card.',
            'benchmark': 'Verify score against the current leaderboard; bump if a newer model leads.',
            'cutoff': 'Verify cutoff date matches the current model\'s actual cutoff (changes with each release).',
        }
        for cat in sorted(by_category.keys()):
            f.write(f'| `{cat}` | {by_category[cat]} | {cat_help.get(cat, "")} |\n')
        f.write('\n## Findings by file\n\n')
        for sp in sorted(by_file.keys()):
            f.write(f'### {sp}\n\n')
            for tag, ctx in by_file[sp]:
                # Escape pipe chars in ctx so it doesn't break tables.
                ctx_safe = ctx.replace('|', '\\|').replace('\n', ' ').strip()
                f.write(f'- `{tag}` &mdash; {ctx_safe[:200]}\n')
            f.write('\n')

    print(f'Wrote refresh queue to {REPORT.relative_to(ROOT)}')
    print(f'Total findings: {total}; categories:')
    for cat in sorted(by_category.keys()):
        print(f'  {cat:18s}: {by_category[cat]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
